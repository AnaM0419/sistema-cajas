-- ---------------------------------------------------------------------
-- PRECIO DE UNA RECARGA
-- Devuelve el TOTAL que se le cobra al cliente.
-- ---------------------------------------------------------------------
create or replace function precio_recarga(p_monto numeric)
returns numeric
language plpgsql
stable
as $$
declare
  r precios_recarga;
begin
  select * into r
  from precios_recarga
  where p_monto >= monto_desde
    and (monto_hasta is null or p_monto <= monto_hasta)
    and vigente_desde <= current_date
    and (vigente_hasta is null or vigente_hasta >= current_date)
  order by prioridad desc, monto_desde desc
  limit 1;

  if not found then
    return round(p_monto, 2);
  end if;

  if r.precio_fijo is not null then
    return r.precio_fijo;
  elsif r.recargo_fijo is not null then
    return round(p_monto + r.recargo_fijo, 2);
  else
    -- siguiente múltiplo ESTRICTAMENTE mayor: 2,15 -> 2,50 y 2,50 -> 3,00
    return round(floor(p_monto / r.redondeo) * r.redondeo + r.redondeo, 2);
  end if;
end;
$$;

