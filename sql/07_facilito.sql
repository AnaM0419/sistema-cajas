-- TODO EL CÁLCULO DE UN MOVIMIENTO DE FACILITO, EN UNA SOLA LLAMADA
-- La pantalla solo dice qué producto y qué valor; esto devuelve lo demás.
-- ---------------------------------------------------------------------
create or replace function calcular_facilito(p_producto bigint, p_monto numeric)
returns table (
  producto_tipo    text,
  total_cobrar     numeric,
  comision_local   numeric,
  comision_prov    numeric,
  ganancia         numeric
)
language plpgsql
stable
as $$
declare
  pr   productos_facilito;
  caja smallint;
  tot  numeric(14,4);
  loc  numeric(14,4);
  prov numeric(14,4);
begin
  select * into pr from productos_facilito where id = p_producto;
  if not found then
    raise exception 'El producto % no existe.', p_producto;
  end if;

  select cj.id into caja from cajas cj where cj.tipo = 'facilito' limit 1;

  -- Lo que el proveedor te reconoce
  if pr.comision_tipo = 'porcentual' then
    prov := round(p_monto * pr.comision_valor / 100, 4);
  else
    prov := pr.comision_valor;
  end if;

  -- Lo que le cobras al cliente
  if pr.tipo = 'recarga' then
    tot := precio_recarga(p_monto);
    loc := round(tot - p_monto, 4);
  else
    loc := coalesce(buscar_tarifa(caja, 'local', 'servicio', null, p_monto), 0);
    tot := round(p_monto + loc, 4);
  end if;

  return query select pr.tipo, tot, loc, prov, round(loc + prov, 4);
end;
$$;

