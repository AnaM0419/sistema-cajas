-- ---------------------------------------------------------------------
-- PRODUCTOS
-- El nombre es el que sale en el comprobante ("MRF - TUENTI - PAQ.").
-- ---------------------------------------------------------------------
create table if not exists productos_facilito (
  id             bigint generated always as identity primary key,
  nombre         text not null unique,
  familia        text not null,              -- MRF · MSP · MTD · TRINITY
  categoria      text,                       -- AGUA, LUZ, COLOMBIA...
  tipo           text not null check (tipo in ('recarga','juego','servicio')),
  comision_tipo  text not null check (comision_tipo in ('porcentual','fija')),
  comision_valor numeric(12,4) not null,     -- % o $ según comision_tipo
  activo         boolean not null default true
);

create index if not exists productos_busqueda on productos_facilito (tipo, nombre);

comment on table productos_facilito is
  'Comisión que Facilito TE RECONOCE por producto. Es ingreso, no costo.';

-- ---------------------------------------------------------------------
-- PRECIOS DE RECARGA
-- Qué se le cobra al cliente según el valor que muestra la plataforma.
-- Cada fila puede resolverse de tres formas, y gana la de mayor prioridad:
--   precio_fijo   -> se cobra ese total exacto
--   recargo_fijo  -> se cobra el valor más ese recargo
--   redondeo      -> se sube al siguiente múltiplo (2,15 -> 2,50)
-- ---------------------------------------------------------------------
create table if not exists precios_recarga (
  id            bigint generated always as identity primary key,
  monto_desde   numeric(14,4) not null,
  monto_hasta   numeric(14,4),              -- null = sin tope
  precio_fijo   numeric(14,4),
  recargo_fijo  numeric(14,4),
  redondeo      numeric(14,4),
  prioridad     smallint not null default 5, -- mayor gana
  vigente_desde date not null default current_date,
  vigente_hasta date,
  notas         text,
  constraint precio_una_regla check (
    (precio_fijo  is not null)::int
  + (recargo_fijo is not null)::int
  + (redondeo     is not null)::int = 1
  )
);

